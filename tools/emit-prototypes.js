#!/usr/bin/env node
/**
 * Turn the harvested building library into Lua the mod loads.
 *
 * `pz-world extract` produces ~7,900 buildings as JSON, which is far more than
 * a mod should ship and is in a format Kahlua cannot read cheaply. This selects
 * a spread of them and writes Lua tables.
 *
 * All four rotations are precomputed here rather than rotated in-game, because
 * rotation needs the tile catalogue's north/west pairing (which sheet's wall
 * matches which) and that catalogue is a 33,000-entry parse of the game's
 * `.tiles.txt` files. Doing it at build time costs disk; doing it at runtime
 * would cost a visible stall in the middle of world generation.
 *
 * The output is derived from The Indie Stone's shipped map data, so it is
 * generated on the player's own machine and is not redistributable — see
 * docs/DECISIONS.md D6.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

import { deserialise } from '../src/extract/harvest.js';
import { rotate } from '../src/prefab/schematic.js';
import { LAYERS } from '../src/prefab/layers.js';
import { loadTileCatalogue } from '../src/formats/tiledefs.js';
import { findInstall } from '../src/lib/pzinstall.js';
import { DEFAULT_LIBRARY } from '../src/extract/run.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');

/**
 * How many prototypes to ship per class. Enough that a street does not repeat
 * itself; few enough that the mod stays a sensible size.
 */
const PER_CLASS = 24;

/** Buildings outside this range are not useful to place. */
const MIN_EDGE = 4;
const MAX_EDGE = 44;

/**
 * Choose a spread of sizes rather than the best-scoring few, so a class can
 * serve both a corner shop and a supermarket.
 */
function selectForClass(entries, count) {
  const usable = entries.filter(
    (e) => e.w >= MIN_EDGE && e.h >= MIN_EDGE && e.w <= MAX_EDGE && e.h <= MAX_EDGE && e.fill >= 0.5,
  );
  if (usable.length <= count) return usable;

  usable.sort((a, b) => a.w * a.h - b.w * b.h);
  const out = [];
  // Even strides through the size-ordered list.
  for (let i = 0; i < count; i++) {
    const idx = Math.floor((i * (usable.length - 1)) / (count - 1));
    if (!out.includes(usable[idx])) out.push(usable[idx]);
  }
  return out;
}

function luaString(s) {
  return `"${String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

/** One rotation, in the exact shape PrefabStructure loads. */
function prefabToLua(schematic, indent = '        ') {
  const { tiles, index } = schematic.palette();
  const lines = [];
  lines.push(`${indent}{`);
  lines.push(`${indent}  dimensions = { ${schematic.w}, ${schematic.h} },`);
  lines.push(`${indent}  zombies = ${schematic.zombies || 0.02},`);
  lines.push(`${indent}  tiles = { ${tiles.map(luaString).join(', ')} },`);
  lines.push(`${indent}  schematic = {`);
  for (const layer of LAYERS) {
    const cells = schematic.layers.get(layer);
    if (!cells.some(Boolean)) continue;
    const rows = [];
    for (let y = 0; y < schematic.h; y++) {
      const row = [];
      for (let x = 0; x < schematic.w; x++) {
        const t = cells[y * schematic.w + x];
        row.push(t ? index.get(t) : 0);
      }
      rows.push(`"${row.join(',')}"`);
    }
    lines.push(`${indent}    ${layer} = { ${rows.join(', ')} },`);
  }
  lines.push(`${indent}  },`);
  lines.push(`${indent}},`);
  return lines.join('\n');
}

export function emitPrototypes({ libraryDir = DEFAULT_LIBRARY, outDir, install, log = () => {} }) {
  const indexFile = path.join(libraryDir, 'index.json');
  if (!fs.existsSync(indexFile)) {
    throw new Error(`no harvested library at ${libraryDir}. Run: npm run extract`);
  }
  const cat = loadTileCatalogue(install ?? findInstall());
  const index = JSON.parse(fs.readFileSync(indexFile, 'utf8'));

  const byClass = new Map();
  for (const e of index.buildings ?? []) {
    let list = byClass.get(e.cls);
    if (!list) byClass.set(e.cls, (list = []));
    list.push(e);
  }

  fs.mkdirSync(outDir, { recursive: true });
  const written = [];
  let totalBytes = 0;

  for (const [cls, entries] of [...byClass].sort()) {
    const chosen = selectForClass(entries, PER_CLASS);
    if (!chosen.length) continue;

    const lines = [];
    lines.push('--[[');
    lines.push(`    Building prototypes: ${cls}`);
    lines.push('');
    lines.push('    Generated by tools/emit-prototypes.js from buildings harvested out of');
    lines.push("    this machine's own Project Zomboid install. Do not edit; regenerate.");
    lines.push('');
    lines.push('    Each entry carries all four rotations, precomputed, because rotating a');
    lines.push("    building needs the game's north/west wall pairing and that table is a");
    lines.push('    33,000-entry parse the mod should not do while the player waits.');
    lines.push(']]');
    lines.push('');
    lines.push('PZWorld = PZWorld or {}');
    lines.push('PZWorld.Prototypes = PZWorld.Prototypes or {}');
    lines.push(`PZWorld.Prototypes[${luaString(cls)}] = {`);

    for (const entry of chosen) {
      const obj = JSON.parse(fs.readFileSync(path.join(libraryDir, entry.file), 'utf8'));
      const base = deserialise(obj);
      const rots = [0, 1, 2, 3].map((t) => rotate(base, cat, t));

      lines.push('  {');
      lines.push(`    name = ${luaString(entry.name)},`);
      lines.push(`    w = ${base.w}, h = ${base.h},`);
      // Room names travel with the prototype so a later loot pass can use them.
      const rooms = [...new Set((obj.roomNames ?? []).filter(Boolean))].slice(0, 12);
      lines.push(`    rooms = { ${rooms.map(luaString).join(', ')} },`);
      lines.push('    rot = {');
      for (const r of rots) lines.push(prefabToLua(r, '      '));
      lines.push('    },');
      lines.push('  },');
    }

    lines.push('}');
    lines.push('');

    const file = path.join(outDir, `${cls}.lua`);
    const body = lines.join('\n');
    fs.writeFileSync(file, body, 'utf8');
    totalBytes += body.length;
    written.push({ cls, count: chosen.length, bytes: body.length });
    log(`  ${cls.padEnd(12)} ${String(chosen.length).padStart(3)} prototypes  ${(body.length / 1024).toFixed(0)} kB`);
  }

  // A loader so the mod requires one file rather than knowing the class list.
  const loader = [
    '--[[ Generated by tools/emit-prototypes.js. Requires every class file. ]]',
    'PZWorld = PZWorld or {}',
    'PZWorld.Prototypes = PZWorld.Prototypes or {}',
    '',
    ...written.map((w) => `require "PZWorld/Prototypes/${w.cls}"`),
    '',
    'return PZWorld.Prototypes',
    '',
  ].join('\n');
  fs.writeFileSync(path.join(outDir, 'init.lua'), loader, 'utf8');

  log(`${written.length} classes, ${(totalBytes / 1024 / 1024).toFixed(1)} MB of Lua`);
  return written;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  emitPrototypes({
    outDir: path.join(ROOT, 'mod/42/media/lua/shared/PZWorld/Prototypes'),
    log: (m) => process.stdout.write(`${m}\n`),
  });
}
